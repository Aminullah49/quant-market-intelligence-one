// Generate 30 candles for realistic chart rendering
export function generateCandlesticks(symbol: string): {
  time: string;
  open: number;
  high: number;
  low: number;
  close: number;
  volume: number;
  marker?: { type: 'HH' | 'HL' | 'LH' | 'LL' | 'BOS' | 'CHOCH' | 'OB' | 'FVG'; label: string };
}[] {
  const foundAsset = DEFAULT_ASSETS.find(a => a.symbol === symbol);
  const basePrice = foundAsset ? foundAsset.price : 1.0800;
  const decimals = basePrice < 10 ? 4 : 2;

  const candles: any[] = [];
  let prevClose = basePrice;

  // Let's create a beautiful uptrending curve with minor pullbacks
  for (let i = 0; i < 30; i++) {
    const isUp = i % 3 !== 0; // Uptrend mostly
    const change = (Math.random() * 0.005 + 0.001) * prevClose;
    const open = prevClose;
    let close = isUp ? open + change : open - change * 0.8;
    
    // Add specific structures
    if (i === 10) close = open - change * 1.5; // swing low
    if (i === 15) close = open + change * 2.2; // expansion (BOS)
    if (i === 22) close = open - change * 1.2; // minor pullback test
    if (i === 28) close = open + change * 1.8; // final HH

    const low = Math.min(open, close) - (Math.random() * 0.0015 * basePrice);
    const high = Math.max(open, close) + (Math.random() * 0.0015 * basePrice);
    prevClose = close;

    const date = new Date();
    date.setHours(date.getHours() - (30 - i) * 4);
    const timeStr = `${date.getMonth()+1}/${date.getDate()} ${date.getHours()}:00`;

    let marker: any = undefined;
    if (i === 5) marker = { type: "HL", label: "HL (Higher Low)" };
    if (i === 12) marker = { type: "LL", label: "Swept Liquidity" };
    if (i === 15) marker = { type: "CHOCH", label: "CHoCH (Shift)" };
    if (i === 19) marker = { type: "OB", label: "H4 Order Block" };
    if (i === 24) marker = { type: "BOS", label: "BOS (Breakout)" };
    if (i === 29) marker = { type: "HH", label: "HH (Higher High)" };

    candles.push({
      time: timeStr,
      open: Number(open.toFixed(decimals)),
      high: Number(high.toFixed(decimals)),
      low: Number(low.toFixed(decimals)),
      close: Number(close.toFixed(decimals)),
      volume: Math.floor(Math.random() * 8000 + 2000),
      marker
    });
  }

  return candles;
}

